module hex7seg(
  input [3:0] in,
  input en,
  output [6:0] out
);
  wire [6:0] seg;
  MuxKeyWithDefault #(16, 4, 7) i0 (seg, in, 7'b1111111, {
    4'b0000, 7'b0000001, 
    4'b0001, 7'b1001111, 
    4'b0010, 7'b0010010, 
    4'b0011, 7'b0000110, 
    4'b0100, 7'b1001100, 
    4'b0101, 7'b0100100, 
    4'b0110, 7'b0100000, 
    4'b0111, 7'b0001111, 
    4'b1000, 7'b0000000, 
    4'b1001, 7'b0000100, 
    4'b1010, 7'b0001000, 
    4'b1011, 7'b1100000,
    4'b1100, 7'b0110001,
    4'b1101, 7'b1000010,
    4'b1110, 7'b0110000,
    4'b1111, 7'b0111000
  });
  assign out = en ? seg : 7'b1111111;
endmodule