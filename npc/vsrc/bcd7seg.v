   4'b0000, 7'b1111110,
   4'b0001, 7'b0110000,
   4'b0010, 7'b1101101,
   4'b0011, 7'b1111001,
   4'b0100, 7'b0110011,
   4'b0101, 7'b1011011,
   4'b0110, 7'b1011111,
   4'b0111, 7'b1110000,
   4'b1000, 7'b1111111,
   4'b1001, 7'b1111011
 });
endmodule
