   4'b0000, 7'b0000001,
   4'b0001, 7'b1001111,
   4'b0010, 7'b0010010,
   4'b0011, 7'b0000110,
   4'b0100, 7'b1001100,
   4'b0101, 7'b0100100,
   4'b0110, 7'b0100000,
   4'b0111, 7'b0001111,
   4'b1000, 7'b0000000,
   4'b1001, 7'b0000100
 });
endmodule
